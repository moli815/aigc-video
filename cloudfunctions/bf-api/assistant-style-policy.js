function styleInstructions(value) {
  let config = value;
  if (typeof config === "string") { try { config = JSON.parse(config); } catch { config = {}; } }
  // Candidate wording failed factual-grounding review. Explicit opt-in only.
  if (!config || typeof config !== "object" || config.enabled !== true) return "";
  const custom = config && typeof config.instructions === "string" ? config.instructions.trim() : "";
  return "【" + VERSION + "】\n" + (custom && custom.length <= 6000 ? custom : DEFAULT_INSTRUCTIONS);
}
